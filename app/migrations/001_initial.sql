CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    google_subject text NOT NULL UNIQUE,
    email text NOT NULL,
    name text NOT NULL
);

CREATE TABLE sessions (
    token_hash bytea PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at timestamptz NOT NULL
);
CREATE INDEX sessions_expiry ON sessions(expires_at);

CREATE TABLE favorites (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title text NOT NULL,
    store_name text NOT NULL,
    deal_url text NOT NULL,
    sale_price numeric(14,2) NOT NULL CHECK (sale_price >= 0),
    normal_price numeric(14,2) NOT NULL CHECK (normal_price >= 0),
    savings numeric(7,2) NOT NULL CHECK (savings BETWEEN 0 AND 100),
    target_price numeric(14,2) CHECK (target_price >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, deal_url)
);

CREATE TABLE connected_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    platform text NOT NULL,
    platform_user_id text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, platform)
);

CREATE TABLE owned_games (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    platform text NOT NULL,
    platform_game_id text NOT NULL,
    title text NOT NULL,
    playtime_minutes integer NOT NULL DEFAULT 0 CHECK (playtime_minutes >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, platform, platform_game_id)
);
